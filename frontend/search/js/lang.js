function updateTextContent() {
    $('[key]').each(function() {
        var key = $(this).attr('key');
        var text = translate(key);

        if ($(this).is('input, textarea')) {
            $(this).attr('placeholder', text);
        } else {
            $(this).text(text);
        }
    });

    updateAutoLanguageLabel();

    $('[data-i18n-title]').each(function() {
        $(this).attr('title', translate($(this).attr('data-i18n-title')));
    });

    $('[data-i18n-aria-label]').each(function() {
        $(this).attr('aria-label', translate($(this).attr('data-i18n-aria-label')));
    });

    $('[data-tooltip-key]').each(function() {
        var key = $(this).attr('data-tooltip-key');
        $(this).find('.tooltip').text(translate(key));
    });

    $('.translate').each(function() {
        var isActive = $(this).attr('id') === languageChoice;
        $(this)
            .toggleClass('active', isActive)
            .attr('aria-pressed', String(isActive));
    });

    updateFooter();
    updateHtmlLang();
}

function refreshTranslatedRuntime() {
    updateTextContent();

    if (typeof updateContent === 'function') {
        updateContent();
    }

    if (typeof seList === 'function') {
        seList();
    }

    if (typeof setSeInit === 'function') {
        setSeInit();
    }

    if (typeof time === 'function') {
        time();
    }
}

$(document).ready(function() {
    refreshTranslatedRuntime();

    $(".translate").click(function() {
        languageChoice = window.YumePreferences.setLanguageChoice($(this).attr("id"));
        lang = window.YumePreferences.resolveLanguage(languageChoice);

        refreshTranslatedRuntime();
        document.dispatchEvent(new CustomEvent('yume:languagechange', {
            detail: { choice: languageChoice, language: lang }
        }));
    });
});

window.syncYumeLanguagePreference = function () {
    var nextChoice = window.YumePreferences.getLanguageChoice();
    var nextLang = window.YumePreferences.resolveLanguage(nextChoice);

    updateAutoLanguageLabel();

    if (nextChoice === languageChoice && nextLang === lang) return false;

    languageChoice = nextChoice;
    lang = nextLang;
    refreshTranslatedRuntime();
    document.dispatchEvent(new CustomEvent('yume:languagechange', {
        detail: { choice: languageChoice, language: lang }
    }));
    return true;
};

// 处理下拉菜单的显示和隐藏
document.addEventListener('DOMContentLoaded', function () {
    const languageContainer = document.querySelector('.language-container');
    const languageIcon = document.querySelector('.language-icon');
    const languageDropdown = document.querySelector('.language-dropdown');
    let languageHideTimer = null;

    if (!languageContainer || !languageIcon || !languageDropdown) return;

    function openLanguageDropdown() {
        clearTimeout(languageHideTimer);
        languageContainer.classList.add('open');
        languageDropdown.classList.add('show-dropdown');
        languageIcon.setAttribute('aria-expanded', 'true');
    }

    function closeLanguageDropdown(delay = 0) {
        clearTimeout(languageHideTimer);
        languageHideTimer = setTimeout(function () {
            languageContainer.classList.remove('open');
            languageDropdown.classList.remove('show-dropdown');
            languageIcon.setAttribute('aria-expanded', 'false');
        }, delay);
    }

    languageIcon.addEventListener('click', function (event) {
        event.stopPropagation();
        if (languageDropdown.classList.contains('show-dropdown')) {
            closeLanguageDropdown();
        } else {
            openLanguageDropdown();
        }
    });

    document.addEventListener('click', function (event) {
        if (!languageContainer.contains(event.target)) {
            closeLanguageDropdown();
        }
    });

    languageContainer.addEventListener('mouseenter', openLanguageDropdown);
    languageContainer.addEventListener('mouseleave', function () {
        closeLanguageDropdown(180);
    });

    languageContainer.addEventListener('focusin', openLanguageDropdown);
    languageContainer.addEventListener('focusout', function (event) {
        if (!languageContainer.contains(event.relatedTarget)) {
            closeLanguageDropdown(120);
        }
    });

    languageDropdown.addEventListener('click', function (event) {
        if (event.target.classList.contains('translate')) {
            closeLanguageDropdown();
        }
    });
});

// DeepL 翻译函数（支持减少 API 调用）
const translateApiUrl = '/api/translate';
const deepLTranslationCache = new Map();

function requestDeepLTranslation(text, targetLang) {
  if (!text) return Promise.resolve(text);

  const cacheKey = `${targetLang}\n${text}`;
  if (deepLTranslationCache.has(cacheKey)) {
    return deepLTranslationCache.get(cacheKey);
  }

  const request = fetch(translateApiUrl, {
    method: 'POST',
    headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
    body: new URLSearchParams({ text, target_lang: targetLang })
  })
  .then((res) => {
    if (!res.ok) {
      throw new Error(`Translate request failed: ${res.status}`);
    }
    return res.json();
  })
  .then((data) => data.translations?.[0]?.text || text)
  .catch((err) => {
    console.error('Translate error', err);
    return text;
  });

  deepLTranslationCache.set(cacheKey, request);
  return request;
}

function translateText(text, targetLang, isCity = false) {

  // ⭐ zh-cn：只有城市名称才调用 DeepL，其余直接返回中文原文
  if (targetLang === "zh-cn") {
    if (!isCity) {
      return Promise.resolve(text); // 天气描述 & 每日一句 → 不翻译
    }

    // 城市名称 → DeepL 简体中文
    return requestDeepLTranslation(text, 'ZH');
  }

  // ⭐ zh-tw：城市名称用 DeepL，其他中文内容用 OpenCC
  if (targetLang === "zh-tw") {
    if (!isCity) {
      const converter = OpenCC.Converter({ from: 'cn', to: 'tw' });
      return Promise.resolve(converter(text)); // 天气描述 & 每日一句 → OpenCC
    }

    // 城市名称 → DeepL 繁体中文
    return requestDeepLTranslation(text, 'ZH-HANT');
  }

  // ⭐ 其他语言：正常 DeepL 翻译
  return requestDeepLTranslation(text, targetLang);
}
