var languageChoice = window.YumePreferences.getLanguageChoice();
var lang = window.YumePreferences.resolveLanguage(languageChoice);

function translate(key) {
    return arrLang[lang]?.[key] || arrLang.en[key] || key;
}

function updateAutoLanguageLabel() {
    var autoOption = document.querySelector('[data-language-auto]');
    if (autoOption) {
        autoOption.textContent = window.YumePreferences.getAutoLanguageLabel();
    }
}

function makeToastButton(key) {
    return '<button type="button">' + translate(key) + '</button>';
}

function updateHtmlLang() {
    var htmlLang = {
        "en": "en",
        "fr": "fr",
        "ja": "ja",
        "zh-cn": "zh-CN",
        "zh-tw": "zh-TW"
    }[lang] || "en";

    document.documentElement.setAttribute('lang', htmlLang);
}

